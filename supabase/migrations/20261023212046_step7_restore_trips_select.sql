-- Step 7: undoes the previous migration. With only "Select own trips" left, each
-- person sees only their own trips again. Its version sorts after the break, so
-- applying the migrations in order always ends with row-level security restored.
--
-- "if exists" makes it safe to run whether or not the policy is still there: on a
-- fresh project it drops it, and on this one it does nothing. Here it was run by hand
-- in Supabase › SQL Editor, because the Supabase MCP server asks for confirmation
-- before a drop and that question couldn't reach the person from the agent's session,
-- so it isn't in the project's migration history (supabase_migrations.schema_migrations).
-- The version is the time this file was added.
drop policy if exists "Step 7: everyone signed in sees every trip" on public.trips;
